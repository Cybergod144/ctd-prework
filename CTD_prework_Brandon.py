# This script determines whether a player qualifies for a bonus shield.
# It asks the user for their current player level and current health percentage.

player_level = int(input("Enter your current player level (1-50): "))
player_health = int(input("Enter your current health percentage (0-100): "))

if player_level <= 10 and player_health < 30:
    print(f"Level {player_level} player with {player_health}% health: Bonus shield activated! Perfect Work Soldier!")
else:
    print(f"Level {player_level} player with {player_health}% health: Not eligible for a bonus shield...but you already knew that.")

